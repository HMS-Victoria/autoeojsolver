#include <stdio.h>

//********** Specification of Digits **********
int Digits(char *s)
// 功能：统计字符串中数字字符的个数
// 参数：s指向一个由英文、数字组成的字符串
// 返回：数字字符的个数
{
    int count = 0;  // 计数器初始化为0
    while (*s != '\0')  // 遍历字符串直到结束
    {
        if (*s >= '0' && *s <= '9')  // 判断当前字符是否为数字
        {
            count++;  // 如果是数字，计数器加1
        }
        s++;  // 指针移动到下一个字符
    }
    return count;  // 返回数字字符的总数
}

/***************************************************************/
int main()
{
    char s[81];  // 定义字符串数组，最大长度为80+1（结束符）
    scanf("%s", s);  // 从标准输入读取字符串
    printf("%d\n", Digits(s));  // 输出数字字符的个数
    return 0;
}